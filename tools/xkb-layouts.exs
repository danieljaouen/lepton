# Generate lib/lepton/wayland/layouts.ex: the keyboard layouts Photon
# offers besides US English, taken from xkeyboard-config (the tables X11
# and Wayland desktops use).
#
#   elixir tools/xkb-layouts.exs XKB_ROOT KEYSYMS_H
#
# XKB_ROOT is xkeyboard-config's share/X11/xkb (Alpine: xkeyboard-config),
# KEYSYMS_H is xkbcommon/xkbcommon-keysyms.h (Alpine: libxkbcommon-dev).
# Only the typing keys' first two levels (plain and Shift) are kept.

[root, keysyms_h] = System.argv()

# {id, file(section), name}
layouts = [
  {"th", "th(basic)", "Thai"},
  {"hi", "in(deva)", "Hindi (InScript)"},
  {"bn", "bd(basic)", "Bengali"},
  {"ta", "in(tam)", "Tamil (InScript)"},
  {"km", "kh(basic)", "Khmer"},
  {"lo", "la(basic)", "Lao"},
  {"my", "mm(basic)", "Burmese"},
  {"ar", "ara(basic)", "Arabic"},
  {"he", "il(basic)", "Hebrew"},
  {"vi", "vn(basic)", "Vietnamese"}
]

# XKB key names => evdev codes (the typing block).
rows = [{"AE", 2, 12}, {"AD", 16, 12}, {"AC", 30, 11}, {"AB", 44, 10}]

names =
  for({prefix, first, n} <- rows, i <- 1..n, into: %{}, do: {"#{prefix}#{String.pad_leading("#{i}", 2, "0")}", first + i - 1})
  |> Map.merge(%{"TLDE" => 41, "BKSL" => 43})

# A keysym's character: the U+ in its comment, or for Latin-1 (and
# 0x1000000 + code point) the value itself.
keysyms =
  for line <- File.stream!(keysyms_h),
      [_, name, value | rest] <- [Regex.run(~r/^#define XKB_KEY_(\w+)\s+0x([0-9a-f]+)(?:.*U\+([0-9A-F]{4,6}))?/, line)],
      v = String.to_integer(value, 16),
      cp = (case rest do [u] -> String.to_integer(u, 16); _ -> cond do v in 0x20..0xFF -> v; v > 0x1000000 -> v - 0x1000000; true -> nil end end),
      cp != nil,
      into: %{},
      do: {name, cp}

char = fn
  "none" -> nil
  "any" -> nil
  "NoSymbol" -> nil
  <<"U", hex::binary>> = s when byte_size(hex) >= 4 -> (if hex =~ ~r/^[0-9a-fA-F]+$/, do: String.to_integer(hex, 16), else: keysyms[s])
  <<"0x", hex::binary>> -> String.to_integer(hex, 16) - 0x1000000
  <<d>> when d in ?0..?9 -> d
  "dead_" <> _ = s -> {:dead, s}
  s -> keysyms[s]
end

defmodule Gen do
  def section(root, spec) do
    {file, sec} =
      case Regex.run(~r/^([\w-]+)(?:\(([\w-]+)\))?$/, spec) do
        [_, f] -> {f, nil}
        [_, f, s] -> {f, s}
      end

    text = File.read!(Path.join([root, "symbols", file]))
    text = Regex.replace(~r{//[^\n]*}, text, "")
    parts = Regex.split(~r/(?=(?:default\s+)?(?:(?:partial|hidden|alphanumeric_keys|modifier_keys|keypad_keys|function_keys|alternate_group)\s+)*xkb_symbols\s+")/, text)
    parts = Enum.filter(parts, &(&1 =~ ~r/xkb_symbols\s+"/))

    body =
      if sec,
        do: Enum.find(parts, &(&1 =~ ~r/xkb_symbols\s+"#{sec}"/)),
        else: Enum.find(parts, &(&1 =~ ~r/^\s*default/)) || hd(parts)

    body || raise "no #{spec}"
  end

  def keys(root, spec) do
    body = section(root, spec)

    Regex.scan(~r/include\s+"([^"]+)"|key\s+<(\w+)>\s*\{([^}]*)\}/, body)
    |> Enum.reduce(%{}, fn
      [_, inc], acc ->
        Enum.reduce(String.split(inc, "+"), acc, fn i, acc -> if i =~ ~r/^level|^nbsp|^keypad|^group/, do: acc, else: Map.merge(acc, keys(root, i)) end)

      [_, "", key, spec], acc ->
        case Regex.run(~r/\[([^\]]*)\]/, spec) do
          [_, syms] -> Map.put(acc, key, syms |> String.split(",") |> Enum.map(&String.trim/1))
          nil -> acc
        end
    end)
  end
end

us = Gen.keys(root, "us(basic)")

data =
  for {id, spec, name} <- layouts do
    keys = Map.merge(us, Gen.keys(root, spec))

    table =
      for {key, code} <- names, syms = keys[key], syms != nil, into: %{} do
        [a | rest] = Enum.map(syms, char)
        b = List.first(rest)
        {code, {a, b || a}}
      end

    {id, name, table}
  end

render = fn
  nil -> "nil"
  {:dead, s} -> ~s({:dead, "#{s}"})
  cp -> "0x#{Integer.to_string(cp, 16)}"
end

out =
  [
    "# Generated by tools/xkb-layouts.exs from xkeyboard-config: do not edit.\n",
    "defmodule Lepton.Wayland.Layouts do\n",
    "  @moduledoc false\n\n",
    "  # id => {name, %{evdev code => {plain, shifted}}}: code points, or {:dead, keysym}.\n",
    "  @layouts %{\n",
    Enum.map_join(data, ",\n", fn {id, name, table} ->
      entries = table |> Enum.sort() |> Enum.map_join(", ", fn {c, {a, b}} -> "#{c} => {#{render.(a)}, #{render.(b)}}" end)
      ~s(    "#{id}" => {"#{name}", %{#{entries}}})
    end),
    "\n  }\n\n",
    "  @order #{inspect(Enum.map(layouts, &elem(&1, 0)))}\n\n",
    "  def ids, do: @order\n",
    "  def get(id), do: @layouts[id]\n",
    "end\n"
  ]

File.write!("lib/lepton/wayland/layouts.ex", out)
IO.puts("wrote lib/lepton/wayland/layouts.ex: #{Enum.map_join(data, ", ", fn {id, _, t} -> "#{id} (#{map_size(t)} keys)" end)}")
